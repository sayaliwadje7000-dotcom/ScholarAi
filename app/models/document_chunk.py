from sqlalchemy import (
    CheckConstraint,
    Column,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    JSON,
    String,
    Text,
    UniqueConstraint,
    Uuid,
    func,
)
from sqlalchemy.orm import relationship

from app.database.base import Base


class DocumentChunk(Base):
    """
    Persistent representation of an extracted document chunk.

    Preserves the deterministic SHA-256 chunk identifier
    generated by the existing document chunking service.
    """

    __tablename__ = "document_chunks"

    __table_args__ = (
        UniqueConstraint(
            "document_id",
            "chunk_index",
            name="uq_document_chunks_document_index",
        ),
        CheckConstraint(
            "chunk_index >= 0",
            name="ck_document_chunks_index_nonnegative",
        ),
        CheckConstraint(
            "character_count >= 0",
            name="ck_document_chunks_character_count",
        ),
        CheckConstraint(
            "word_count >= 0",
            name="ck_document_chunks_word_count",
        ),
        CheckConstraint(
            "token_count IS NULL OR token_count >= 0",
            name="ck_document_chunks_token_count",
        ),
        CheckConstraint(
            "start_page IS NULL OR start_page > 0",
            name="ck_document_chunks_start_page_positive",
        ),
        CheckConstraint(
            "end_page IS NULL OR end_page > 0",
            name="ck_document_chunks_end_page_positive",
        ),
        Index(
            "ix_document_chunks_document_id",
            "document_id",
        ),
        Index(
            "ix_document_chunks_content_hash",
            "content_hash",
        ),
    )

    chunk_id = Column(
        String(64),
        primary_key=True,
    )

    document_id = Column(
        Uuid(as_uuid=True),
        ForeignKey(
            "documents.id",
            ondelete="CASCADE",
        ),
        nullable=False,
    )

    chunk_index = Column(
        Integer,
        nullable=False,
    )

    text = Column(
        Text,
        nullable=False,
    )

    content_hash = Column(
        String(64),
        nullable=False,
    )

    page_numbers = Column(
        JSON,
        nullable=False,
        default=list,
    )

    start_page = Column(
        Integer,
        nullable=True,
    )

    end_page = Column(
        Integer,
        nullable=True,
    )

    character_count = Column(
        Integer,
        nullable=False,
    )

    word_count = Column(
        Integer,
        nullable=False,
    )

    token_count = Column(
        Integer,
        nullable=True,
    )

    chunking_version = Column(
        String(50),
        nullable=False,
        default="1.0",
        server_default="1.0",
    )

    created_at = Column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    document = relationship(
        "Document",
        back_populates="chunks",
    )

    embeddings = relationship(
        "ChunkEmbedding",
        back_populates="chunk",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )