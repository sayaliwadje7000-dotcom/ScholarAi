"""Baseline machine-learning models for ScholarAI recommendations."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Sequence

import numpy as np

from scipy.sparse import issparse

from sklearn.dummy import DummyClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.utils.validation import check_array

from app.services.recommendations.ml.dataset_schema import (
    DatasetLabel,
)

from app.services.recommendations.ml.models.model_config import (
    BaselineModelConfig,
)


class BaselineModelError(Exception):
    """Base exception for baseline model errors."""


class BaselineModelNotFittedError(BaselineModelError):
    """Raised when prediction is requested before training."""


class InvalidTrainingDataError(BaselineModelError):
    """Raised when training data violates model requirements."""


@dataclass(frozen=True, slots=True)
class FeatureCoefficient:
    """Feature coefficient and its direction of influence."""

    feature_name: str

    coefficient: float

    direction: str


@dataclass(frozen=True, slots=True)
class BaselineTrainingSummary:
    """Metadata describing a completed training operation."""

    model_name: str

    training_samples: int

    feature_count: int

    classes: tuple[int, ...]

    converged: bool

    iterations: int


class RecommendationBaselineModel:
    """
    Logistic Regression relevance classifier.

    Input:
        Numerical feature matrix generated by Phase 14.3.

    Target:
        0 = Not relevant
        1 = Relevant

    Output:
        Predicted relevance class and relevance probability.
    """

    MODEL_NAME = "scholarai_logistic_regression_baseline"

    MODEL_VERSION = "1.0.0"

    def __init__(
        self,
        config: BaselineModelConfig | None = None,
    ) -> None:

        self.config = config or BaselineModelConfig()

        self.estimator = LogisticRegression(
            C=self.config.regularization_strength,
            max_iter=self.config.max_iterations,
            tol=self.config.tolerance,
            class_weight=self.config.class_weight,
            random_state=self.config.random_state,
            solver=self.config.solver,
        )

        self._is_fitted = False

        self._feature_count: int | None = None

        self._feature_names: tuple[str, ...] | None = None

        self._training_summary: BaselineTrainingSummary | None = None

    @staticmethod
    def _validate_matrix(
        X: Any,
    ) -> Any:
        """Validate dense or sparse numerical feature matrices."""

        try:

            matrix = check_array(
                X,
                accept_sparse="csr",
                dtype=np.float64,
                ensure_2d=True,
            )

        except (TypeError, ValueError) as exc:

            raise InvalidTrainingDataError(
                "Feature matrix must contain valid finite numerical values"
            ) from exc

        if matrix.shape[0] == 0:
            raise InvalidTrainingDataError(
                "Feature matrix cannot be empty"
            )

        if matrix.shape[1] == 0:
            raise InvalidTrainingDataError(
                "Feature matrix must contain at least one feature"
            )

        return matrix

    @staticmethod
    def _validate_labels(
        y: Any,
        expected_samples: int,
    ) -> np.ndarray:
        """Validate binary relevance labels."""

        try:

            labels = np.asarray(y)

        except Exception as exc:

            raise InvalidTrainingDataError(
                "Unable to convert labels into an array"
            ) from exc

        if labels.ndim != 1:
            raise InvalidTrainingDataError(
                "Labels must be a one-dimensional array"
            )

        if len(labels) != expected_samples:
            raise InvalidTrainingDataError(
                "Feature and label sample counts do not match"
            )

        if not np.isin(
            labels,
            [
                int(DatasetLabel.NOT_RELEVANT),
                int(DatasetLabel.RELEVANT),
            ],
        ).all():

            raise InvalidTrainingDataError(
                "Labels must contain only 0 and 1"
            )

        labels = labels.astype(np.int64)

        unique_classes = np.unique(labels)

        if len(unique_classes) != 2:

            raise InvalidTrainingDataError(
                "Logistic Regression requires both relevance classes"
            )

        return labels

    @staticmethod
    def _validate_feature_names(
        feature_names: Sequence[str] | None,
        feature_count: int,
    ) -> tuple[str, ...] | None:

        if feature_names is None:
            return None

        names = tuple(feature_names)

        if len(names) != feature_count:
            raise InvalidTrainingDataError(
                "Feature name count does not match matrix dimensions"
            )

        if any(
            not isinstance(name, str) or not name.strip()
            for name in names
        ):
            raise InvalidTrainingDataError(
                "Feature names must be non-empty strings"
            )

        if len(set(names)) != len(names):
            raise InvalidTrainingDataError(
                "Feature names must be unique"
            )

        return names

    @staticmethod
    def _validate_sample_weight(
        sample_weight: Any,
        expected_samples: int,
    ) -> np.ndarray | None:

        if sample_weight is None:
            return None

        weights = np.asarray(
            sample_weight,
            dtype=np.float64,
        )

        if weights.ndim != 1:
            raise InvalidTrainingDataError(
                "Sample weights must be one-dimensional"
            )

        if len(weights) != expected_samples:
            raise InvalidTrainingDataError(
                "Sample weight count does not match training samples"
            )

        if not np.isfinite(weights).all():
            raise InvalidTrainingDataError(
                "Sample weights must be finite"
            )

        if (weights < 0).any():
            raise InvalidTrainingDataError(
                "Sample weights cannot be negative"
            )

        if weights.sum() <= 0:
            raise InvalidTrainingDataError(
                "At least one sample weight must be positive"
            )

        return weights

    def fit(
        self,
        X: Any,
        y: Any,
        *,
        feature_names: Sequence[str] | None = None,
        sample_weight: Any = None,
    ) -> BaselineTrainingSummary:
        """
        Train the Logistic Regression baseline.

        Feature transformation must already have been fitted
        on training data only.
        """

        matrix = self._validate_matrix(X)

        labels = self._validate_labels(
            y,
            expected_samples=matrix.shape[0],
        )

        names = self._validate_feature_names(
            feature_names,
            feature_count=matrix.shape[1],
        )

        weights = self._validate_sample_weight(
            sample_weight,
            expected_samples=matrix.shape[0],
        )

        try:

            self.estimator.fit(
                matrix,
                labels,
                sample_weight=weights,
            )

        except Exception as exc:

            raise BaselineModelError(
                "Logistic Regression training failed"
            ) from exc

        self._feature_count = matrix.shape[1]

        self._feature_names = names

        self._is_fitted = True

        iterations = int(
            np.max(self.estimator.n_iter_)
        )

        converged = (
            iterations < self.config.max_iterations
        )

        self._training_summary = BaselineTrainingSummary(
            model_name=self.MODEL_NAME,
            training_samples=matrix.shape[0],
            feature_count=matrix.shape[1],
            classes=tuple(
                int(value)
                for value in self.estimator.classes_
            ),
            converged=converged,
            iterations=iterations,
        )

        return self._training_summary

    def _check_ready(self) -> None:

        if not self._is_fitted:
            raise BaselineModelNotFittedError(
                "Train the model before requesting predictions"
            )

    def _validate_prediction_matrix(
        self,
        X: Any,
    ) -> Any:

        self._check_ready()

        matrix = self._validate_matrix(X)

        if matrix.shape[1] != self._feature_count:

            raise InvalidTrainingDataError(
                "Prediction feature dimensions do not match training"
            )

        return matrix

    def predict(
        self,
        X: Any,
    ) -> np.ndarray:
        """Predict relevance labels."""

        matrix = self._validate_prediction_matrix(X)

        return self.estimator.predict(matrix)

    def predict_proba(
        self,
        X: Any,
    ) -> np.ndarray:
        """Predict class probabilities."""

        matrix = self._validate_prediction_matrix(X)

        return self.estimator.predict_proba(matrix)

    def predict_relevance_probability(
        self,
        X: Any,
    ) -> np.ndarray:
        """Return the probability that a resource is relevant."""

        probabilities = self.predict_proba(X)

        relevant_index = np.where(
            self.estimator.classes_
            == int(DatasetLabel.RELEVANT)
        )[0]

        if len(relevant_index) != 1:
            raise BaselineModelError(
                "Relevant class is missing from the trained model"
            )

        return probabilities[:, relevant_index[0]]

    def get_feature_coefficients(
        self,
        top_n: int = 20,
    ) -> tuple[FeatureCoefficient, ...]:
        """Inspect the strongest positive and negative coefficients."""

        self._check_ready()

        if top_n < 1:
            raise ValueError(
                "top_n must be positive"
            )

        coefficients = self.estimator.coef_[0]

        if self._feature_names is None:

            names = tuple(
                f"feature_{index}"
                for index in range(len(coefficients))
            )

        else:

            names = self._feature_names

        ranked_indices = np.argsort(
            np.abs(coefficients)
        )[::-1][:top_n]

        result = []

        for index in ranked_indices:

            value = float(coefficients[index])

            result.append(
                FeatureCoefficient(
                    feature_name=names[index],
                    coefficient=value,
                    direction=(
                        "positive"
                        if value > 0
                        else "negative"
                        if value < 0
                        else "neutral"
                    ),
                )
            )

        return tuple(result)

    @property
    def is_fitted(self) -> bool:

        return self._is_fitted

    @property
    def training_summary(
        self,
    ) -> BaselineTrainingSummary:

        self._check_ready()

        return self._training_summary


class RecommendationDummyBaseline:
    """
    Non-learning reference classifier.

    Uses the training-set class distribution to establish
    a reference against which the learned model can be compared.
    """

    MODEL_NAME = "scholarai_dummy_prior_baseline"

    def __init__(self) -> None:

        self.estimator = DummyClassifier(
            strategy="prior"
        )

        self._is_fitted = False

        self._feature_count: int | None = None

    def fit(
        self,
        X: Any,
        y: Any,
    ) -> "RecommendationDummyBaseline":

        matrix = RecommendationBaselineModel._validate_matrix(
            X
        )

        labels = np.asarray(y)

        if labels.ndim != 1:
            raise InvalidTrainingDataError(
                "Labels must be one-dimensional"
            )

        if len(labels) != matrix.shape[0]:
            raise InvalidTrainingDataError(
                "Feature and label sample counts do not match"
            )

        if not np.isin(labels, [0, 1]).all():
            raise InvalidTrainingDataError(
                "Labels must contain only 0 and 1"
            )

        self.estimator.fit(
            matrix,
            labels.astype(np.int64),
        )

        self._feature_count = matrix.shape[1]

        self._is_fitted = True

        return self

    def predict(
        self,
        X: Any,
    ) -> np.ndarray:

        matrix = self._validate_prediction_matrix(X)

        return self.estimator.predict(matrix)

    def predict_proba(
        self,
        X: Any,
    ) -> np.ndarray:

        matrix = self._validate_prediction_matrix(X)

        return self.estimator.predict_proba(matrix)

    def _validate_prediction_matrix(
        self,
        X: Any,
    ) -> Any:

        if not self._is_fitted:
            raise BaselineModelNotFittedError(
                "Train the dummy baseline before prediction"
            )

        matrix = RecommendationBaselineModel._validate_matrix(
            X
        )

        if matrix.shape[1] != self._feature_count:
            raise InvalidTrainingDataError(
                "Prediction feature dimensions do not match training"
            )

        return matrix