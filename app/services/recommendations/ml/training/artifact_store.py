"""Persistence for trained ScholarAI recommendation model artifacts."""

from __future__ import annotations

import os
import tempfile

from pathlib import Path
from typing import Any

import joblib

from app.services.recommendations.ml.features.feature_schema import (
    FEATURE_SCHEMA_VERSION,
)

from app.services.recommendations.ml.models.baseline_model import (
    RecommendationBaselineModel,
)

from app.services.recommendations.ml.training.training_pipeline import (
    TrainingResult,
)


ARTIFACT_FORMAT_VERSION = "1.0"


class ModelArtifactError(Exception):
    """Raised when model artifact operations fail."""


class ModelArtifactStore:
    """
    Stores and retrieves trained model artifacts.

    Only load artifacts generated by trusted ScholarAI processes.
    Joblib files use Python serialization and must not be loaded
    from untrusted sources.
    """

    @staticmethod
    def _artifact_payload(
        result: TrainingResult,
    ) -> dict[str, Any]:

        return {
            "artifact_format_version": ARTIFACT_FORMAT_VERSION,

            "model_name": (
                result.model.MODEL_NAME
            ),

            "model_version": (
                result.model.MODEL_VERSION
            ),

            "run_id": result.run_id,

            "trained_at": result.trained_at.isoformat(),

            "model": result.model,

            "dummy_baseline": result.dummy_baseline,

            "feature_transformer": (
                result.feature_transformer
            ),

            "feature_schema_version": (
                FEATURE_SCHEMA_VERSION
            ),

            "feature_names": result.feature_names,

            "training_config": result.config,

            "training_summary": result.training_summary,

            "training_statistics": (
                result.training_statistics
            ),

            "validation_statistics": (
                result.validation_statistics
            ),

            "training_class_distribution": (
                result.training_class_distribution
            ),

            "validation_class_distribution": (
                result.validation_class_distribution
            ),
        }

    def save(
        self,
        result: TrainingResult,
        destination: str | Path,
    ) -> Path:
        """
        Atomically persist a completed training run.

        Temporary files are created in the destination directory
        so the final replacement remains on the same filesystem.
        """

        path = Path(destination)

        if path.suffix != ".joblib":
            raise ModelArtifactError(
                "Model artifacts must use the .joblib extension"
            )

        try:

            path.parent.mkdir(
                parents=True,
                exist_ok=True,
            )

            payload = self._artifact_payload(result)

            file_descriptor, temporary_name = tempfile.mkstemp(
                prefix=f".{path.stem}_",
                suffix=".tmp",
                dir=path.parent,
            )

            os.close(file_descriptor)

            temporary_path = Path(temporary_name)

            try:

                joblib.dump(
                    payload,
                    temporary_path,
                    compress=3,
                )

                os.replace(
                    temporary_path,
                    path,
                )

            finally:

                if temporary_path.exists():
                    temporary_path.unlink()

            return path

        except ModelArtifactError:
            raise

        except Exception as exc:

            raise ModelArtifactError(
                "Unable to save model artifact"
            ) from exc

    def load(
        self,
        source: str | Path,
    ) -> dict[str, Any]:
        """
        Load a trusted ScholarAI model artifact.

        This method validates artifact metadata after deserialization.
        It does not make untrusted joblib files safe.
        """

        path = Path(source)

        if not path.is_file():
            raise ModelArtifactError(
                "Model artifact does not exist"
            )

        if path.suffix != ".joblib":
            raise ModelArtifactError(
                "Unsupported model artifact extension"
            )

        try:

            payload = joblib.load(path)

        except Exception as exc:

            raise ModelArtifactError(
                "Unable to load model artifact"
            ) from exc

        if not isinstance(payload, dict):
            raise ModelArtifactError(
                "Invalid model artifact structure"
            )

        if (
            payload.get("artifact_format_version")
            != ARTIFACT_FORMAT_VERSION
        ):
            raise ModelArtifactError(
                "Unsupported artifact format version"
            )

        if (
            payload.get("feature_schema_version")
            != FEATURE_SCHEMA_VERSION
        ):
            raise ModelArtifactError(
                "Feature schema version mismatch"
            )

        if not isinstance(
            payload.get("model"),
            RecommendationBaselineModel,
        ):
            raise ModelArtifactError(
                "Invalid recommendation model in artifact"
            )

        if not payload["model"].is_fitted:
            raise ModelArtifactError(
                "Stored recommendation model is not fitted"
            )

        return payload